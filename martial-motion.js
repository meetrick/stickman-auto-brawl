export function martialTrack(f) {
  if (f.weapon !== 'None' || !f.attack) return null;
  const { name, signature, variant } = f.attack, tracks = MARTIAL_TRACKS[f.style];
  if (!tracks) return null;
  if (signature && name === (f.style === 'Boxing' ? 'Punch' : 'Kick')) return tracks.signature;
  if (name === 'Kick' && variant === 1 && tracks.Roundhouse) return tracks.Roundhouse;
  if (name === 'Punch' && variant === 1) {
    if (tracks.Cross) return tracks.Cross;
    // Rear-hand versions retain the discipline's body/feet, swapping hands.
    return tracks.Punch.map(([t, lean, crouch, mx, my, ox, oy, ...feet]) => [t, lean, crouch, ox, oy, mx, my, ...feet]);
  }
  return tracks[name] || null;
}
